namespace Maliev.ShadcnBlazor.Components.DataDisplay;

/// <summary>Defines the native scope relationship of a table heading cell.</summary>
public enum ShadcnTableHeadScope
{
    /// <summary>The heading applies to its column.</summary>
    Column,
    /// <summary>The heading applies to its row.</summary>
    Row,
    /// <summary>The heading applies to its column group.</summary>
    ColumnGroup,
    /// <summary>The heading applies to its row group.</summary>
    RowGroup
}
